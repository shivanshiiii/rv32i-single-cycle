#!/usr/bin/env python3
"""Build a reproducible RV32I demo ROM with labels and metadata, no dependencies."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
PROGRAMS = ROOT / 'programs'


from rv32i_encode import r, i, shift_i, s, b, u, j


# Use tuple opcodes here so the assembly is readable, but encoding is generated.
program = []
labels = {}

def label(name):
    labels[name] = len(program) * 4

def emit(mnemonic, *args):
    program.append((mnemonic, args))

emit('addi', 1, 0, 7)
emit('addi', 2, 0, 5)
emit('add', 3, 1, 2)
emit('sub', 4, 1, 2)
emit('and', 5, 1, 2)
emit('or', 6, 1, 2)
emit('xor', 7, 1, 2)
emit('sll', 8, 2, 1)
emit('srl', 9, 8, 1)
emit('slt', 10, 2, 1)
emit('sra', 11, 8, 2)
emit('addi', 12, 0, -8)
emit('srai', 13, 12, 2)
emit('andi', 14, 1, 3)
emit('ori', 15, 2, 2)
emit('xori', 16, 1, 3)
emit('slti', 17, 12, 0)
emit('slli', 18, 2, 2)
emit('srli', 19, 18, 1)
emit('sw', 3, 0, 12)
emit('lw', 20, 0, 12)
emit('beq', 20, 3, 'branch_a')
emit('addi', 21, 0, 99)  # MUST BE SKIPPED
label('branch_a')
emit('bne', 1, 2, 'branch_b')
emit('addi', 21, 0, 98)  # MUST BE SKIPPED
label('branch_b')
emit('lui', 22, 0x12345)
emit('auipc', 23, 1)
emit('jal', 24, 'jal_target')
emit('addi', 25, 0, 55)  # MUST BE SKIPPED
label('jal_target')
emit('addi_label', 27, 0, 'jalr_target')
emit('jalr', 26, 27, 0)
emit('addi', 25, 0, 77)  # MUST BE SKIPPED
label('jalr_target')
emit('blt', 2, 1, 'blt_target')
emit('addi', 21, 0, 97)  # MUST BE SKIPPED
label('blt_target')
emit('bge', 1, 2, 'bge_target')
emit('addi', 21, 0, 96)  # MUST BE SKIPPED
label('bge_target')
emit('sltu', 28, 2, 1)
emit('sltiu', 29, 2, 6)
emit('sub', 30, 2, 1)
emit('sra', 31, 30, 2)
label('halt')
emit('jal', 0, 'halt')

r_f3 = {'add': (0, 0), 'sub': (32, 0), 'and': (0, 7), 'or': (0, 6),
        'xor': (0, 4), 'slt': (0, 2), 'sltu': (0, 3), 'sll': (0, 1),
        'srl': (0, 5), 'sra': (32, 5)}
i_f3 = {'addi': 0, 'andi': 7, 'ori': 6, 'xori': 4, 'slti': 2, 'sltiu': 3}
branch_f3 = {'beq': 0, 'bne': 1, 'blt': 4, 'bge': 5}
words = []
listing = []
for pc_index, (op, args) in enumerate(program):
    pc = pc_index * 4
    if op in r_f3:
        rd, rs1, rs2 = args
        f7, f3 = r_f3[op]
        word = r(f7, rs2, rs1, f3, rd)
    elif op in i_f3:
        rd, rs1, imm = args
        word = i(imm, rs1, i_f3[op], rd)
    elif op == 'addi_label':
        rd, rs1, lbl = args
        word = i(labels[lbl], rs1, 0, rd)
    elif op in ('slli', 'srli', 'srai'):
        rd, rs1, shamt = args
        f7, f3 = (32, 5) if op == 'srai' else ((0, 1) if op == 'slli' else (0, 5))
        word = shift_i(f7, shamt, rs1, f3, rd)
    elif op == 'lw':
        rd, rs1, imm = args
        word = i(imm, rs1, 2, rd, 0x03)
    elif op == 'sw':
        rs2, rs1, imm = args
        word = s(imm, rs2, rs1)
    elif op in branch_f3:
        rs1, rs2, target = args
        word = b(labels[target]-pc, rs2, rs1, branch_f3[op])
    elif op == 'lui':
        rd, imm = args
        word = u(imm, rd, 0x37)
    elif op == 'auipc':
        rd, imm = args
        word = u(imm, rd, 0x17)
    elif op == 'jal':
        rd, target = args
        word = j(labels[target]-pc, rd)
    elif op == 'jalr':
        rd, rs1, imm = args
        word = i(imm, rs1, 0, rd, 0x67)
    else:
        raise ValueError(op)
    words.append(word)
    listing.append(f'{pc:04x}: {word:08x}  {op} '+', '.join(map(str, args)))

PROGRAMS.mkdir(exist_ok=True)
assert len(words) <= 256, 'Demo program exceeds instruction memory'
rom_words = words + [0x00000013] * (256 - len(words))
(PROGRAMS/'demo.hex').write_text('\n'.join(f'{word:08x}' for word in rom_words)+'\n')
(PROGRAMS/'demo.lst').write_text('\n'.join(listing)+'\n')
(PROGRAMS/'demo_meta.json').write_text(json.dumps({'halt_pc': labels['halt'], 'labels': labels,
                                                   'instruction_count':len(words)}, indent=2)+'\n')
(ROOT/'tb'/'demo_expected.vh').write_text(
    '// Generated by tools/build_program.py; do not edit manually.\n'
    + f"localparam [31:0] HALT_PC = 32'd{labels['halt']};\n"
    + f"localparam [31:0] JALR_TARGET_PC = 32'd{labels['jalr_target']};\n"
    + f"localparam [31:0] AUIPC_RESULT = 32'd{labels['branch_b']+4+4096};\n"
    + f"localparam [31:0] JAL_LINK = 32'd{labels['jal_target']-4};\n"
    + f"localparam [31:0] JALR_LINK = 32'd{labels['jalr_target']-4};\n"
)
print(f'Generated {len(words)} instructions; halt @ byte address {labels["halt"]}.')
