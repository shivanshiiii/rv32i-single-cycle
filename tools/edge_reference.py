#!/usr/bin/env python3
"""Check signedness, branch fall-through, loops and jumps in Python.

This is an independent architectural reference check, NOT Verilog simulation.
"""
from pathlib import Path
import json
from isa_reference import run_rom

ROOT = Path(__file__).resolve().parents[1]
meta = json.loads((ROOT / 'programs/edge_meta.json').read_text())
result = run_rom(ROOT / 'programs/edge.hex', meta['halt_pc'])
regs, ram = result['regs'], result['ram']
expected = {
    0: 0, 1: 0xffffffff, 2: 1, 3: 1, 4: 0, 5: 1, 6: 0, 7: 1,
    8: 0xffffffff, 9: 1, 10: 0x80000000, 11: 0xc0000000,
    12: 0x40000000, 13: 0, 14: 0xffffffff, 15: 0xfffff800,
    16: 2047, 17: 0xfffff800, 18: 0xffffffff, 19: 0,
    20: 0x80000000, 21: 1, 22: 0xffffffff, 23: 15, 24: 0,
    25: 0, 26: 1, 27: 33, 28: 0x80000000,
    29: meta['labels']['forward_jump'] - 4,
    30: meta['labels']['forward_jump'],
    31: meta['labels']['forward_jump'] + 8,
}
for reg, value in expected.items():
    assert regs[reg] == value, f'x{reg} expected {value:#010x}, got {regs[reg]:#010x}'
assert ram[7] == 0x80000000, f'RAM[7] unexpected {ram[7]:#x}'
branches = result['branch_events']
for pc in (0x58, 0x60, 0x68, 0x70):
    assert (pc, False) in [(p, t) for p, _, t in branches], f'Branch not-taken failed at {pc:#x}'
for pc in (0x78, 0x80, 0x88, 0x90):
    assert (pc, True) in [(p, t) for p, _, t in branches], f'Branch taken failed at {pc:#x}'
assert [(p, t) for p, _, t in branches if p == 0xa0] == [
    (0xa0, True), (0xa0, True), (0xa0, False)
], 'Counted loop did not execute expected branch sequence'
assert 0xbc not in result['trace'] and 0xc8 not in result['trace'], 'Jump delay slot executed'
# Save expected PC sequence for optional cycle-by-cycle RTL checking.
(ROOT / 'programs/edge_trace.hex').write_text(
    '\n'.join(f'{pc:08x}' for pc in result['trace']) + '\n'
)
(ROOT / 'tb/edge_trace_expected.vh').write_text(
    '// Generated by tools/edge_reference.py; do not edit manually.\n'
    + f'localparam integer EDGE_TRACE_STEPS = {len(result["trace"])};\n'
)
print(f'PASS: Python edge reference: {len(result["trace"])} executed instructions, '
      f'{len(expected)} registers, 11 branch outcomes, RAM[7]')
print('NOTE: Python reference is NOT an RTL simulation.')
